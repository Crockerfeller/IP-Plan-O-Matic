/* Subnetting practice for IP Plan-O-Matic: random questions, checked answers, and the working shown.
   Hand-written (not generated by tools/build_learn.py). The math uses plain arithmetic, not bitwise operators,
   so addresses above 128.0.0.0 don't turn negative. tests/features.html checks it against Python's ipaddress. */
(() => {
  'use strict';
  // ---------- IPv4 math ----------
  const toInt = (s) => s.split('.').reduce((a, o) => a * 256 + Number(o), 0);
  const toIp = (n) => [Math.floor(n / 16777216) % 256, Math.floor(n / 65536) % 256, Math.floor(n / 256) % 256, n % 256].join('.');
  const size = (p) => 2 ** (32 - p);
  const maskOf = (p) => toIp(2 ** 32 - size(p));
  const wildOf = (p) => toIp(size(p) - 1);
  const netOf = (ip, p) => ip - (ip % size(p));
  const hostsOf = (p) => (p === 32 ? 1 : p === 31 ? 2 : size(p) - 2);
  const firstOf = (ip, p) => netOf(ip, p) + (p >= 31 ? 0 : 1);
  const lastOf = (ip, p) => netOf(ip, p) + size(p) - (p >= 31 ? 1 : 2);
  const bcastOf = (ip, p) => netOf(ip, p) + size(p) - 1;
  const fmt = (n) => n.toLocaleString('en-US');

  // The answer to each kind of question, as text. Exposed for the tests.
  const answer = (kind, ip, p, extra) => {
    switch (kind) {
      case 'network': return toIp(netOf(ip, p));
      case 'broadcast': return toIp(bcastOf(ip, p));
      case 'first': return toIp(firstOf(ip, p));
      case 'last': return toIp(lastOf(ip, p));
      case 'mask': return maskOf(p);
      case 'wildcard': return wildOf(p);
      case 'hosts': return String(hostsOf(p));
      case 'prefix': return '/' + p;
      case 'fit': { let q = 30; while (q > 0 && hostsOf(q) < extra) q--; while (q < 30 && hostsOf(q + 1) >= extra) q++; return '/' + q; }
      case 'count': return String(2 ** (extra - p));
      case 'same': return netOf(ip, p) === netOf(extra, p) ? 'yes' : 'no';
      default: throw new Error('unknown kind ' + kind);
    }
  };

  // ---------- How to work it out: the block-size method ----------
  const OCT = ['first', 'second', 'third', 'last'];
  const blockNote = (p) => {
    if (p % 8 === 0) return `A /${p} ends on an octet boundary: keep the first ${p / 8} octet${p === 8 ? '' : 's'} and the rest are 0 for the network.`;
    const o = Math.floor(p / 8), block = 2 ** (8 * (o + 1) - p);
    return `A /${p} has a block size of ${block} in the ${OCT[o]} octet (256 − ${256 - block}, from the mask ${maskOf(p)}).`;
  };
  const octetWork = (ip, p) => {
    if (p % 8 === 0) return '';
    const o = Math.floor(p / 8), block = 2 ** (8 * (o + 1) - p), v = toIp(ip).split('.').map(Number)[o];
    const lo = v - (v % block);
    return ` ${v} falls in the block ${lo}–${lo + block - 1}.`;
  };
  const explain = (q) => {
    const { kind, ip, p, extra } = q, cidr = `${toIp(ip)}/${p}`;
    switch (kind) {
      case 'network': return `${blockNote(p)}${octetWork(ip, p)} So the network of ${cidr} is ${answer('network', ip, p)}.`;
      case 'broadcast': return `${blockNote(p)}${octetWork(ip, p)} The broadcast is the last address of that block: ${answer('broadcast', ip, p)}.`;
      case 'first': return `The network is ${answer('network', ip, p)}${p >= 31 ? ` and on a /${p} every address is usable` : '; the first usable host is one more'}: ${answer('first', ip, p)}.`;
      case 'last': return `The broadcast is ${answer('broadcast', ip, p)}${p >= 31 ? ` and on a /${p} every address is usable` : '; the last usable host is one less'}: ${answer('last', ip, p)}.`;
      case 'mask': return `${p} ones then ${32 - p} zeros. ${blockNote(p)}`;
      case 'wildcard': return `The wildcard is the mask ${maskOf(p)} inverted: 255 minus each octet gives ${wildOf(p)}.`;
      case 'hosts': return p >= 31 ? `A /${p} is special: ${p === 31 ? 'both addresses are usable on a point-to-point link (RFC 3021)' : 'it is a single address'}.` : `2^(32 − ${p}) = ${fmt(size(p))} addresses, minus the network and broadcast: ${fmt(hostsOf(p))}.`;
      case 'prefix': return `Count the 1 bits in ${maskOf(p)}: ${p}. ${blockNote(p)}`;
      case 'fit': { const a = Number(answer('fit', 0, 0, extra).slice(1)); return `A /${a} holds ${fmt(hostsOf(a))} hosts and a /${a + 1} only ${fmt(hostsOf(a + 1))}, so ${fmt(extra)} hosts need a /${a}.`; }
      case 'count': return `Each step from /${p} to /${extra} doubles the count: 2^(${extra} − ${p}) = ${answer('count', 0, p, extra)}.`;
      case 'same': return `${blockNote(p)} ${toIp(ip)} is in ${answer('network', ip, p)}/${p} and ${toIp(extra)} is in ${answer('network', extra, p)}/${p}.`;
      default: return '';
    }
  };

  // ---------- Questions ----------
  const LEVELS = {
    easy: { lo: 24, hi: 30, base: () => [192, 168, null] },
    medium: { lo: 16, hi: 30, base: () => [10, null, null] },
    hard: { lo: 8, hi: 30, base: () => [null, null, null] },
  };
  const KINDS = {
    network: 'Network address', broadcast: 'Broadcast address', first: 'First usable host', last: 'Last usable host',
    mask: 'Subnet mask from prefix', prefix: 'Prefix from subnet mask', wildcard: 'Wildcard mask', hosts: 'Usable hosts',
    fit: 'Smallest subnet for N hosts', count: 'Subnets inside a subnet', same: 'Same subnet or not',
  };
  const ipFor = (level, rnd) => {
    const b = LEVELS[level].base();
    const pick = (lo, hi) => lo + Math.floor(rnd() * (hi - lo + 1));
    const o1 = b[0] ?? pick(1, 223), o2 = b[1] ?? pick(0, 255), o3 = b[2] ?? pick(0, 255);
    return ((o1 * 256 + o2) * 256 + o3) * 256 + pick(0, 255);
  };
  const make = (kind, level, rnd = Math.random) => {
    const L = LEVELS[level], pick = (lo, hi) => lo + Math.floor(rnd() * (hi - lo + 1));
    const p = pick(L.lo, L.hi), ip = ipFor(level, rnd), cidr = `${toIp(ip)}/${p}`;
    switch (kind) {
      case 'network': return { kind, ip, p, text: `What is the network address of ${cidr}?` };
      case 'broadcast': { const q = Math.min(p, 30); return { kind, ip, p: q, text: `What is the broadcast address of ${toIp(ip)}/${q}?` }; }
      case 'first': return { kind, ip, p: Math.min(p, 30), text: `What is the first usable host in ${toIp(ip)}/${Math.min(p, 30)}?` };
      case 'last': return { kind, ip, p: Math.min(p, 30), text: `What is the last usable host in ${toIp(ip)}/${Math.min(p, 30)}?` };
      case 'mask': return { kind, ip, p, text: `What is the subnet mask for a /${p}?` };
      case 'prefix': return { kind, ip, p, text: `Subnet mask ${maskOf(p)} is which prefix length?` };
      case 'wildcard': return { kind, ip, p, text: `What is the wildcard mask for a /${p}?` };
      case 'hosts': { const q = level === 'easy' ? p : pick(L.lo, 32); return { kind, ip, p: q, text: `How many usable hosts are in a /${q}?` }; }
      case 'fit': {
        const q = Math.min(Math.max(p, 17), 29), lo = hostsOf(q + 1) + 1, hi = hostsOf(q);   // /29 is the smallest with a gap below it
        const n = pick(lo, hi);
        return { kind, ip, p: q, extra: n, text: `What is the smallest subnet that holds ${fmt(n)} hosts?` };
      }
      case 'count': { const a = Math.min(p, 28), b = pick(a + 1, Math.min(a + 6, 30)); return { kind, ip, p: a, extra: b, text: `How many /${b} subnets fit in a /${a}?` }; }
      case 'same': {
        const q = Math.max(p, L.lo), base = netOf(ip, q);
        const other = rnd() < 0.5 ? base + pick(0, size(q) - 1) : Math.min(2 ** 32 - 1, base + size(q) + pick(0, size(q) - 1));
        return { kind, ip, p: q, extra: other, text: `Are ${toIp(ip)} and ${toIp(other)} in the same /${q}?` };
      }
      default: throw new Error('unknown kind ' + kind);
    }
  };
  // What the person typed, made comparable: spaces and commas out, a prefix with or without "/", yes/no words.
  const normalize = (kind, s) => {
    let t = String(s).trim().toLowerCase().replace(/[\s,]+/g, '');
    if (kind === 'prefix' || kind === 'fit') t = '/' + t.replace(/^\//, '');
    if (kind === 'same') t = /^(y|yes|true)$/.test(t) ? 'yes' : /^(n|no|false)$/.test(t) ? 'no' : t;
    if (/^(network|broadcast|first|last|mask|wildcard)$/.test(kind)) t = t.split('.').map((o) => (/^\d+$/.test(o) ? String(Number(o)) : o)).join('.');
    return t;
  };
  const isRight = (q, input) => normalize(q.kind, input) === answer(q.kind, q.ip, q.p, q.extra);

  window.ipomPractice = { answer, make, isRight, explain, toInt, toIp, KINDS };

  // ---------- The page ----------
  const $ = (id) => document.getElementById(id);
  if (!$('quiz')) return;
  const KEY = 'ipom.practice';
  let score = { right: 0, total: 0, streak: 0, best: 0 };
  try { score = { ...score, ...JSON.parse(localStorage.getItem(KEY) || '{}') }; } catch (e) { /* storage unavailable */ }
  const save = () => { try { localStorage.setItem(KEY, JSON.stringify(score)); } catch (e) { /* ignore */ } };
  const kindsBox = $('qKinds');
  for (const [k, label] of Object.entries(KINDS)) {
    const l = document.createElement('label');
    l.innerHTML = `<input type="checkbox" value="${k}" checked> ${label}`;
    kindsBox.appendChild(l);
  }
  let q = null, answered = false;
  const showScore = () => {
    $('qScore').textContent = `${score.right} / ${score.total}`;
    $('qStreak').textContent = `streak ${score.streak} · best ${score.best}`;
  };
  const next = () => {
    const kinds = [...kindsBox.querySelectorAll('input:checked')].map((c) => c.value);
    if (!kinds.length) { $('qText').textContent = 'Pick at least one question type.'; return; }
    q = make(kinds[Math.floor(Math.random() * kinds.length)], $('qLevel').value);
    answered = false;
    $('qText').textContent = q.text;
    $('qIn').value = '';
    $('qIn').placeholder = q.kind === 'same' ? 'yes or no' : /prefix|fit/.test(q.kind) ? 'e.g. /26' : /hosts|count/.test(q.kind) ? 'a number' : 'e.g. 10.0.0.0';
    $('qFb').hidden = true;
    $('qCheck').textContent = 'Check';
    $('qIn').focus();
  };
  const reveal = (ok) => {
    answered = true;
    const fb = $('qFb');
    fb.hidden = false;
    fb.className = 'qfb ' + (ok ? 'ok' : 'bad');
    fb.innerHTML = '';
    const head = document.createElement('b');
    head.textContent = ok ? 'Correct.' : `The answer is ${answer(q.kind, q.ip, q.p, q.extra)}.`;
    const why = document.createElement('span');
    why.textContent = ' ' + explain(q);
    fb.append(head, why);
    $('qCheck').textContent = 'Next question';
  };
  $('qForm').addEventListener('submit', (e) => {
    e.preventDefault();
    if (!q || answered) { next(); return; }
    if (!$('qIn').value.trim()) return;
    const ok = isRight(q, $('qIn').value);
    score.total++;
    if (ok) { score.right++; score.streak++; score.best = Math.max(score.best, score.streak); } else score.streak = 0;
    save(); showScore(); reveal(ok);
  });
  $('qSkip').addEventListener('click', () => { if (q && !answered) { score.streak = 0; save(); showScore(); reveal(false); } else next(); });
  $('qReset').addEventListener('click', () => { score = { right: 0, total: 0, streak: 0, best: 0 }; save(); showScore(); });
  $('qLevel').addEventListener('change', next);
  kindsBox.addEventListener('change', next);
  showScore();
  next();
})();
